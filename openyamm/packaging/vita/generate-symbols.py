"""Build the explicit loader registry. Missing imports remain failures, never return-success stubs."""
import json
import re
from pathlib import Path

root = Path(__file__).parent
audit = json.loads(Path('work/elf-audit.json').read_text())
imports = set(audit['imports'])
direct = set('''abort acos acosf asin asinf atan atan2 atan2f atoi bsearch calloc cbrt ceil ceilf
cos cosf cosh exit exp exp2 fabs floor floorf fmax fmaxf fminf fmod fmodf free frexp getenv hypot hypotf
ldexp ldexpf llrint llrintf llround log log10 log2 logf lrint lrintf lround lroundf malloc memchr
memcmp memcpy memmove memset pow powf printf pthread_detach pthread_getspecific pthread_join
pthread_key_create pthread_key_delete pthread_self pthread_setspecific qsort realloc rint round roundf
scalbn sin sincos sincosf sinf sinh snprintf sscanf strchr strcmp strcoll strcpy strcspn strdup strlen
strncmp strncpy strnlen strpbrk strrchr strspn strstr strtod strtof strtol strtoll strtoul strtoull
tan tanf tanh trunc vasprintf vsnprintf vsscanf wcslen wmemchr __cxa_atexit __cxa_finalize
freelocale getuid iswlower_l mallinfo posix_memalign strtold_l strtoll_l strtoull_l uselocale'''.split())
direct.update(name for name in imports if name.startswith('SDL_'))
sources = ['bridge-runtime.c', 'bridge-paths.c', 'bridge-random.c', 'bridge-runtime-generated.c', 'bridge-files.c', 'bridge-threads.c',
    'bridge-time.c', 'bridge-multibyte.c', 'bridge-system.c', 'bridge-locale.c', 'bridge-loader.c',
    'bridge-graphics.c', 'bridge-input.c', 'bridge-memory.c']
mapping = {name: name for name in imports & direct}
for name in sources:
    text = (root / name).read_text()
    for function in re.findall(r'\b(oy_\w+)\([^;{}]*\)\s*\{', text):
        symbol = function[3:]
        if symbol in imports:
            mapping[symbol] = function
for name in ['__sF', 'stdin', 'stdout', 'stderr', '__stack_chk_guard']:
    mapping[name] = '&oy_' + name
mapping['setjmp'] = 'oy_setjmp'
mapping['longjmp'] = 'oy_longjmp'
mapping['eglGetError'] = 'oy_eglGetError'
mapping['oy_house_metrics'] = 'oy_house_metrics'
mapping['oy_stall_frame'] = 'oy_stall_frame'
mapping['setvbuf'] = 'oy_setvbuf'
mapping['pthread_mutexattr_destroy'] = 'oy_pthread_mutexattr_destroy'

text = '''// Generated by generate-symbols.py.
#define _GNU_SOURCE
#include <SDL3/SDL.h>
#include <SDL3/SDL_vulkan.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <wchar.h>
#include "so_util.h"
extern int __cxa_atexit(void (*pDestructor)(void *), void *pObject, void *pDso);
extern void __cxa_finalize(void *pDso);
extern int oy_setjmp(void *pBuffer) __attribute__((returns_twice));
extern void oy_longjmp(void *pBuffer, int value) __attribute__((noreturn));
'''
text += ''.join(f'#include "{name}"\n' for name in sources)
text += '\nconst so_default_dynlib *oy_get_symbols(size_t *pCount)\n{\n'
text += '    static const so_default_dynlib symbols[] =\n    {\n'
text += ''.join(f'        {{"{name}", (uintptr_t){function}}},\n' for name, function in sorted(mapping.items()))
text += '    };\n    *pCount = sizeof(symbols) / sizeof(symbols[0]);\n    return symbols;\n}\n'
(root / 'bridge-symbols-generated.c').write_text(text)
remaining = sorted(imports - mapping.keys())
report = {'registered': len(imports & mapping.keys()), 'graphics_to_resolve':
    [n for n in remaining if n.startswith(('gl', 'egl'))],
    'system_remaining': [n for n in remaining if not n.startswith(('gl', 'egl'))]}
Path('work/bridge-coverage.json').write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))
